# Variablen

a = 10
b = 5
c = 3

#addition
summe = a + b + c
print("Die Summe ergibt:", summe)

#Subtraktion
differenz = a - b
print("Die Differenz beträgt:", differenz)

#Multiplikation
produkt = a * b
print("Das Ergebnis der Multiplikation beträgt:", produkt)

#Division
quotient = a / b
print("Der Quotient beträgt:", quotient)

#Ganzzahlige Division
ganzzahl_quotient = a // c
print("Der Ganzzahlige Quotient beträgt:", ganzzahl_quotient)

#Modulo (gibt den Rest einer Division)
rest = a % c
print("Der Rest der Division beträgt:", rest)

#Potenzierung
potenz = 2 **c
print("2 hoch 3 ergibt:", potenz)

